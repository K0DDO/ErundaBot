def _build_deck() -> tuple[TarotCard, ...]:
    cards: list[TarotCard] = []
    for index, (name_ru, name_en, upright, reversed_) in enumerate(_MAJORS):
        cards.append(TarotCard(f"major_{index:02d}", name_ru, name_en, upright, reversed_))
    for suit_id, suit_ru, suit_en in _SUITS:
        meanings = _MINOR_MEANINGS[suit_id]
        for rank_index, (rank_ru, rank_en) in enumerate(_RANKS):
            upright, reversed_ = meanings[rank_index]
            cards.append(
                TarotCard(
                    f"{suit_id}_{rank_index + 1:02d}",
                    f"{rank_ru} {suit_ru}",
                    f"{rank_en} of {suit_en}",
                    upright,
                    reversed_,
                )
            )
    return tuple(cards)


TAROT_DECK: tuple[TarotCard, ...] = _build_deck()
TAROT_BY_ID: dict[str, TarotCard] = {card.id: card for card in TAROT_DECK}

"""Rider–Waite–Smith tarot deck: names, short meanings, image files."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class TarotCard:
    id: str
    name_ru: str
    name_en: str
    upright: str
    reversed: str

    @property
    def title(self) -> str:
        return f"{self.name_ru} ({self.name_en})"

    def image_name(self, reversed_: bool) -> str:
        return f"{self.id}_r.jpg" if reversed_ else f"{self.id}.jpg"


